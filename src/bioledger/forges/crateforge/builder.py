from __future__ import annotations

import logging
import tempfile
from pathlib import Path

from rocrate.rocrate import ROCrate

from bioledger.ledger.models import EntryKind, LedgerEntry, LedgerSession

logger = logging.getLogger(__name__)


def _generate_nextflow_config(entries: list[LedgerEntry]) -> str:
    """Generate nextflow.config with profile-based container runtime selection.

    Emits profile blocks for docker, singularity, and conda. The profile
    matching the original execution (docker if any docker entries, conda if
    any conda entries) is uncommented by default. Others are available via
    ``-profile <name>``. Includes commented-out Slurm and SGE examples.
    """
    has_docker = any(e.executor == "docker" for e in entries)
    has_conda = any(e.executor == "conda" for e in entries)
    has_engine = any(
        e.executor in ("snakemake", "galaxy", "nextflow") for e in entries
    )

    lines = [
        "// Auto-generated by BioLedger.",
        "// Select a container runtime profile with:",
        "//   nextflow run workflow.nf -profile docker",
        "// Or uncomment the active profile below.",
    ]

    if has_engine:
        lines.append(
            "// Engine runtimes: conda env create -f engine-env.yml"
        )

    lines.append("")
    lines.append("profiles {")

    # Docker profile
    if has_docker:
        lines.append("    docker {")
        lines.append("        docker.enabled = true")
        lines.append("    }")
    else:
        lines.append("    // docker {")
        lines.append("    //     docker.enabled = true")
        lines.append("    // }")

    # Singularity profile (commented out — uncomment for HPC/Singularity)
    if not has_docker and not has_conda:
        lines.append("    singularity {")
        lines.append("        singularity.enabled = true")
        lines.append("    }")
    else:
        lines.append("    // singularity {")
        lines.append("    //     singularity.enabled = true")
        lines.append("    // }")

    # Conda profile
    if has_conda:
        lines.append("    conda {")
        lines.append("        conda.enabled = true")
        lines.append("    }")
    else:
        lines.append("    // conda {")
        lines.append("    //     conda.enabled = true")
        lines.append("    // }")

    # Slurm example (commented)
    lines.append("    // Slurm cluster — uncomment and customize")
    lines.append("    // slurm {")
    lines.append("    //     process.executor = 'slurm'")
    lines.append("    //     process.queue = 'normal'")
    lines.append("    //     process.time = '12h'")
    lines.append("    //     process.cpus = 4")
    lines.append("    // }")

    lines.append("}")

    # manifest block: pin nextflow version if any entry used nextflow natively
    nf_entries = [e for e in entries if e.executor == "nextflow" and e.executor_version]
    if nf_entries:
        # Extract semver from the recorded version string (e.g. "nextflow 23.10.0")
        from bioledger.core.engines.versions import _extract_version
        nf_ver = _extract_version("nextflow", nf_entries[0].executor_version)
        lines.append("")
        lines.append("manifest {")
        lines.append(f"    nextflowVersion = '>={nf_ver}'")
        lines.append("}")

    return "\n".join(lines) + "\n"


def _generate_snakefile_from_entry(entry: LedgerEntry) -> str | None:
    """Generate a Snakefile representation from a fan-out ledger entry."""
    from bioledger.core.engines.conda_derive import resolve_container_from_spec
    from bioledger.core.engines.snakemake_adapter import _generate_snakefile
    from bioledger.toolspec.models import ExecutionSpec

    spec_snapshot = entry.tool_spec_snapshot or {}
    if not spec_snapshot:
        return None

    try:
        spec = ExecutionSpec(**spec_snapshot)
    except Exception:
        return None

    input_mapping = entry.container.input_mapping if entry.container else {}
    container_image = resolve_container_from_spec(spec)

    with tempfile.NamedTemporaryFile(suffix=".smk", delete=False) as tmp:
        artifact_path = Path(tmp.name)

    try:
        _generate_snakefile(spec, input_mapping, container_image, artifact_path)
        return artifact_path.read_text()
    except Exception as e:
        logger.warning("Failed to generate Snakefile from entry %s: %s", entry.id, e)
        return None
    finally:
        artifact_path.unlink(missing_ok=True)


def _add_engine_supplementary_files(
    crate: ROCrate,
    scratch: Path,
    entries: list[LedgerEntry],
    session_dir: Path | None,
) -> None:
    """Add engine-specific supplementary files to the crate.

    For snakemake entries: generate .smk rule files.
    For galaxy entries: copy tool XML from tool_dir (via _engine_metadata sidecar).
    For nextflow entries: copy module files from module_dir (via sidecar).
    """
    import json

    for entry in entries:
        if entry.executor == "snakemake":
            smk_content = _generate_snakefile_from_entry(entry)
            if smk_content:
                tool_name = entry.tool_spec_name or "tool"
                rule_name = tool_name.replace("-", "_")
                dest = f"{rule_name}.smk"
                smk_path = scratch / dest
                smk_path.write_text(smk_content)
                crate.add_file(
                    str(smk_path),
                    dest_path=dest,
                    properties={
                        "description": f"Snakemake rule for {tool_name}",
                        "programmingLanguage": "snakemake",
                    },
                )
        elif entry.executor in ("galaxy", "nextflow"):
            if not session_dir:
                logger.warning(
                    "Cannot add supplementary files for entry %s — "
                    "session_dir not provided",
                    entry.id,
                )
                continue
            meta_path = session_dir / f"_engine_metadata_{entry.id}.json"
            if meta_path.exists():
                meta = json.loads(meta_path.read_text())
                dir_key = "tool_dir" if entry.executor == "galaxy" else "module_dir"
                src_dir = meta.get(dir_key)
                if src_dir and Path(src_dir).exists():
                    if entry.executor == "galaxy":
                        glob_pattern = "*.xml"
                    else:
                        relevant_exts = (".nf", ".yml", ".yaml", ".md", ".conf")
                        for f in Path(src_dir).iterdir():
                            if not f.is_file() or f.suffix not in relevant_exts:
                                continue
                            dest = f"{entry.tool_spec_name}/{f.name}"
                            f_path = scratch / dest
                            f_path.parent.mkdir(parents=True, exist_ok=True)
                            f_path.write_bytes(f.read_bytes())
                            crate.add_file(
                                str(f_path),
                                dest_path=dest,
                                properties={
                                    "description": (
                                        f"Nextflow module for {entry.tool_spec_name}"
                                    ),
                                },
                            )
                        continue
                    for f in Path(src_dir).glob(glob_pattern):
                        if not f.is_file():
                            continue
                        dest = f"{entry.tool_spec_name}/{f.name}"
                        f_path = scratch / dest
                        f_path.parent.mkdir(parents=True, exist_ok=True)
                        f_path.write_bytes(f.read_bytes())
                        crate.add_file(
                            str(f_path),
                            dest_path=dest,
                            properties={
                                "description": (
                                    f"Galaxy tool XML for {entry.tool_spec_name}"
                                    if entry.executor == "galaxy"
                                    else f"Nextflow module for {entry.tool_spec_name}"
                                ),
                            },
                        )


def build_rocrate(
    session: LedgerSession,
    output_dir: Path,
    entry_ids: list[str] | None = None,
    include_running: bool = False,
    session_dir: Path | None = None,
) -> Path:
    """Package a ledger session (or subset) as an RO-Crate.

    Args:
        session: The full session
        output_dir: Where to write crate files
        entry_ids: If provided, only include these entries (user-selected subset).
                   If None, include all entries.
        include_running: If True, include entries with run_status "running"
                         in the Nextflow workflow.
        session_dir: Optional session directory path, needed to locate
                     _engine_metadata sidecars for engine supplementary files.

    Always produces a single ``workflow.nf`` as mainEntity, orchestrating
    all executors (docker, conda, snakemake, galaxy, nextflow) as Nextflow
    processes. Engine-specific supplementary files (.smk, tool XML, nf-core
    modules) are included alongside. An ``engine-env.yml`` conda env file is
    generated if any engine entries are present.
    """
    crate = ROCrate()
    output_dir.mkdir(parents=True, exist_ok=True)

    # Filter entries if subset requested
    if entry_ids is not None:
        selected_ids = set(entry_ids)
        entries = [e for e in session.entries if e.id in selected_ids]
    else:
        entries = session.entries

    # Add data files from selected entries
    added_files: set[str] = set()
    for entry in entries:
        for fref in entry.files:
            dedup_key = f"{entry.id}:{fref.path}"
            if dedup_key in added_files:
                continue
            p = Path(fref.path)
            if p.exists():
                dest = f"{entry.id[:8]}/{p.name}"
                crate.add_file(
                    str(p),
                    dest_path=dest,
                    properties={
                        "description": f"{fref.role} for {entry.kind.value}",
                        "sha256": fref.sha256,
                    },
                )
                added_files.add(dedup_key)

    with tempfile.TemporaryDirectory() as scratch_dir:
        scratch = Path(scratch_dir)

        tool_entries = [
            e for e in entries if e.kind in (EntryKind.TOOL_RUN, EntryKind.SCRIPT_RUN)
        ]
        if tool_entries:
            # Always crystallize into a single Nextflow workflow
            from bioledger.forges.analysisforge.crystallize import (
                generate_engine_env_yml,
                to_nextflow_from_entries,
            )

            nf_content = to_nextflow_from_entries(
                tool_entries, include_running=include_running
            )
            nf_path = scratch / "workflow.nf"
            nf_path.write_text(nf_content)
            crate.add_workflow(
                str(nf_path),
                dest_path="workflow.nf",
                main=True,
                lang="nextflow",
            )

            config_content = _generate_nextflow_config(tool_entries)
            config_path = scratch / "nextflow.config"
            config_path.write_text(config_content)
            crate.add_file(
                str(config_path),
                dest_path="nextflow.config",
                properties={
                    "description": "Nextflow configuration for running the workflow"
                },
            )

            # Add engine-specific supplementary files
            _add_engine_supplementary_files(
                crate, scratch, tool_entries, session_dir
            )

            # Add engine-env.yml if any engine entries present
            env_yml = generate_engine_env_yml(tool_entries)
            if env_yml:
                env_path = scratch / "engine-env.yml"
                env_path.write_text(env_yml)
                crate.add_file(
                    str(env_path),
                    dest_path="engine-env.yml",
                    properties={
                        "description": "Conda env file for engine runtimes"
                    },
                )

        # Add filtered ledger as provenance
        filtered_session = session.model_copy()
        filtered_session.entries = entries
        ledger_path = scratch / "ledger.json"
        ledger_path.write_text(filtered_session.model_dump_json(indent=2))
        crate.add_file(
            str(ledger_path),
            dest_path="ledger.json",
            properties={"description": "BioLedger provenance log (selected entries)"},
        )

        crate_dir = output_dir / "ro-crate"
        crate.write(str(crate_dir))

    return crate_dir
