"""Galaxy adapter — local execution via planemo or remote via bioblend.

Implements all five ``ExecutionAdapter`` methods:
- ``submit_spec()``: run a workflow toolspec via Galaxy
- ``generate()``: produce a Galaxy .ga workflow definition for fan-out
- ``submit()``: submit the workflow to a Galaxy instance
- ``poll()``: check workflow invocation status
- ``collect()``: collect outputs from completed Galaxy history

Two modes:
- ``planemo`` (default): local Galaxy instance via planemo (pip-installable)
- ``remote``: connect to an existing Galaxy server via bioblend

Includes a tool-availability check: before running, the adapter queries
the Galaxy instance's tool panel to verify the toolspec's tool exists.
If not, errors with a clear message — no Docker fallback.
"""

from __future__ import annotations

import json
import logging
import os
import shutil
import subprocess
import time
from pathlib import Path
from typing import Any

from bioledger.core.engines.conda_derive import resolve_container_from_spec
from bioledger.core.engines.config import GalaxyEngineConfig
from bioledger.core.engines.protocol import (
    RunHandle,
    RunStatus,
    WorkflowHandle,
    build_output_patterns,
    split_collection_inputs,
)

logger = logging.getLogger(__name__)


def _check_planemo_available() -> str:
    """Return the planemo executable path, or raise with install instructions."""
    exe = shutil.which("planemo")
    if exe is None:
        raise RuntimeError(
            "planemo is not installed. Install with: pip install bioledger[galaxy]"
        )
    return exe


def _resolve_container(spec: Any) -> str:
    """Resolve the container image from spec.container or spec.conda_deps.

    .. deprecated:: Use ``resolve_container_from_spec`` from
        ``conda_derive`` directly.
    """
    return resolve_container_from_spec(spec)


def _generate_galaxy_workflow(
    spec: Any,
    input_mapping: dict[str, str],
    artifact_path: Path,
) -> tuple[list[str], list[str]]:
    """Generate a Galaxy .ga workflow definition for fan-out.

    Returns (step_names, collection_inputs).
    """
    spec_outputs = getattr(spec, "outputs", {}) or {}
    tool_name = getattr(spec, "name", "tool")
    container_image = resolve_container_from_spec(spec)

    collection_inputs, single_inputs = split_collection_inputs(
        spec, input_mapping
    )

    # Build Galaxy workflow JSON
    tool_id = tool_name
    tool_version = "latest"
    if container_image and ":" in container_image:
        tool_version = container_image.split(":")[-1]

    # Build input connections
    input_connections: dict[str, dict] = {}
    for name in single_inputs:
        input_connections[name] = {"id": 0, "output_name": "output"}

    # Build outputs
    outputs: dict[str, dict] = {}
    for out_name in spec_outputs:
        outputs[out_name] = {"type": "data", "name": out_name}

    workflow = {
        "a_galaxy_workflow": "true",
        "format-version": "0.1",
        "name": f"BioLedger fan-out: {tool_name}",
        "annotation": f"Generated by BioLedger for {tool_name}",
        "steps": {
            "0": {
                "id": 0,
                "type": "data_input",
                "tool_id": None,
                "tool_version": None,
                "name": "Input dataset",
                "inputs": [{"name": "input"}],
                "position": {"left": 100, "top": 100},
            },
            "1": {
                "id": 1,
                "type": "tool",
                "tool_id": tool_id,
                "tool_version": tool_version,
                "name": tool_name,
                "input_connections": input_connections,
                "outputs": outputs,
                "position": {"left": 300, "top": 100},
            },
        },
    }

    # If collection inputs, add a data collection input step
    if collection_inputs:
        workflow["steps"]["2"] = {
            "id": 2,
            "type": "data_collection_input",
            "tool_id": None,
            "tool_version": None,
            "name": f"Input collection: {collection_inputs[0]}",
            "inputs": [{"name": collection_inputs[0]}],
            "position": {"left": 100, "top": 300},
        }
        # Wire the collection to the tool step
        workflow["steps"]["1"]["input_connections"][collection_inputs[0]] = {
            "id": 2,
            "output_name": "output",
        }

    artifact_path.parent.mkdir(parents=True, exist_ok=True)
    artifact_path.write_text(json.dumps(workflow, indent=2))
    return [tool_name], collection_inputs


class GalaxyAdapter:
    """Galaxy adapter for local (planemo) or remote (bioblend) execution.

    In planemo mode, launches a local Galaxy instance via planemo and
    submits workflows to it. In remote mode, connects to an existing
    Galaxy server via bioblend.

    Includes a tool-availability check before submission: queries the
    Galaxy instance's tool panel to verify the tool exists. If not,
    raises an error with a clear message — no Docker fallback.
    """

    def __init__(self, config: GalaxyEngineConfig | None = None) -> None:
        self._config = config or GalaxyEngineConfig()
        self._bioblend_client = None

    @property
    def executable(self) -> str:
        if self._config.executable:
            return self._config.executable
        if self._config.mode == "planemo":
            return _check_planemo_available()
        raise RuntimeError(
            "Remote Galaxy mode requires bioblend. "
            "Install with: pip install bioledger[galaxy]"
        )

    def _get_bioblend_client(self):
        """Get or create a bioblend GalaxyClient for remote mode."""
        if self._bioblend_client is not None:
            return self._bioblend_client
        try:
            from bioblend.galaxy import GalaxyInstance
        except ImportError:
            raise RuntimeError(
                "bioblend is not installed. "
                "Install with: pip install bioledger[galaxy]"
            )
        self._bioblend_client = GalaxyInstance(
            url=self._config.url,
            key=self._config.api_key or "",
        )
        return self._bioblend_client

    def _check_tool_availability(self, tool_id: str) -> None:
        """Check if a tool is available in the Galaxy instance.

        Raises RuntimeError if the tool is not found — no Docker fallback.
        """
        if self._config.mode == "remote":
            client = self._get_bioblend_client()
            tools = client.tools.get_tools()
            tool_ids = {t.get("id", "") for t in tools}
            if tool_id not in tool_ids:
                raise RuntimeError(
                    f"Tool '{tool_id}' is not available in this Galaxy instance "
                    f"({self._config.url}). No Docker fallback — install the "
                    f"tool in Galaxy or use a different engine."
                )
        else:
            # planemo mode: check if the tool is in the local tool panel
            # For now, we trust that planemo serves the tool if it's in
            # the configured tool directory. A full check would query
            # the planemo server's API.
            logger.info(
                "Tool availability check skipped in planemo mode for %s",
                tool_id,
            )

    def submit_spec(
        self,
        spec: Any,
        input_mapping: dict[str, str],
        params: dict[str, Any],
        work_dir: Path,
    ) -> RunHandle:
        """Run a single workflow toolspec via Galaxy.

        Checks tool availability first, then submits to the Galaxy instance.
        """
        raise NotImplementedError(
            "GalaxyAdapter.submit_spec will be wired when dispatch() is "
            "unified with the agent path."
        )

    def generate(
        self,
        spec: Any,
        input_mapping: dict[str, str],
        extra_args: list[str] | None = None,
    ) -> WorkflowHandle:
        """Generate a Galaxy .ga workflow definition for fan-out."""
        import tempfile
        artifact_path = Path(tempfile.gettempdir()) / f"bioledger_galaxy_{int(time.time())}.ga"

        step_names, collection_inputs = _generate_galaxy_workflow(
            spec, input_mapping, artifact_path
        )

        output_patterns = build_output_patterns(spec)

        return WorkflowHandle(
            executor="galaxy",
            artifact_path=artifact_path,
            step_inventory=step_names,
            container_image="",
            input_mapping=input_mapping,
            output_patterns=output_patterns,
            metadata={
                "extra_args": extra_args or [],
                "collection_inputs": collection_inputs,
            },
        )

    def submit(
        self,
        handle: WorkflowHandle,
        input_mapping: dict[str, str],
        params: dict[str, Any],
        work_dir: Path,
    ) -> RunHandle:
        """Submit the generated Galaxy workflow.

        In planemo mode: starts a local Galaxy server and submits the workflow.
        In remote mode: submits to the configured Galaxy server via bioblend.
        """
        work_dir = Path(work_dir)
        work_dir.mkdir(parents=True, exist_ok=True)

        # Copy the workflow to the work dir
        ga_path = work_dir / "workflow.ga"
        ga_path.write_text(handle.artifact_path.read_text())

        # Check tool availability
        tool_name = handle.step_inventory[0] if handle.step_inventory else "unknown"
        self._check_tool_availability(tool_name)

        if self._config.mode == "planemo":
            return self._submit_planemo(handle, work_dir, ga_path)
        else:
            return self._submit_remote(handle, work_dir, ga_path)

    def _submit_planemo(
        self, handle: WorkflowHandle, work_dir: Path, ga_path: Path
    ) -> RunHandle:
        """Submit via planemo local Galaxy instance."""
        cmd = [
            self.executable,
            "serve",
            "galaxy",
            "--galaxy-root",
            str(work_dir / "galaxy"),
            "--port", "8765",
        ]
        extra_args = handle.metadata.get("extra_args", [])
        cmd.extend(extra_args)
        cmd.extend(self._config.extra_args)

        log_path = work_dir / "galaxy.log"
        log_file = open(log_path, "w")
        proc = subprocess.Popen(
            cmd,
            cwd=str(work_dir),
            stdout=log_file,
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )

        return RunHandle(
            executor="galaxy",
            run_id=str(proc.pid),
            entry_id="",
            work_dir=work_dir,
            submitted_at=time.strftime(
                "%Y-%m-%dT%H:%M:%SZ", time.gmtime()
            ),
            status="running",
        )

    def _submit_remote(
        self, handle: WorkflowHandle, work_dir: Path, ga_path: Path
    ) -> RunHandle:
        """Submit via bioblend to a remote Galaxy server."""
        client = self._get_bioblend_client()

        # Import the workflow
        workflow_content = ga_path.read_text()
        imported = client.workflows.import_workflow_dict(
            json.loads(workflow_content)
        )
        workflow_id = imported.get("id", "")

        # Create a new history
        history = client.histories.create_history(
            name=f"BioLedger_{int(time.time())}"
        )
        history_id = history.get("id", "")

        # Run the workflow
        invocation = client.workflows.invoke_workflow(
            workflow_id,
            history_id=history_id,
        )
        invocation_id = invocation.get("id", "")

        return RunHandle(
            executor="galaxy",
            run_id=invocation_id,
            entry_id="",
            work_dir=work_dir,
            submitted_at=time.strftime(
                "%Y-%m-%dT%H:%M:%SZ", time.gmtime()
            ),
            status="running",
        )

    def poll(self, run_handle: RunHandle) -> RunStatus | None:
        """Check if the Galaxy job is still running."""
        if self._config.mode == "planemo":
            return self._poll_planemo(run_handle)
        else:
            return self._poll_remote(run_handle)

    def _poll_planemo(self, run_handle: RunHandle) -> RunStatus | None:
        """Poll planemo local Galaxy process."""
        try:
            pid = int(run_handle.run_id)
        except ValueError:
            return None

        try:
            os.kill(pid, 0)
        except ProcessLookupError:
            return self._check_completion_planemo(run_handle)
        except PermissionError:
            return None

        return RunStatus(state="running", message="")

    def _poll_remote(self, run_handle: RunHandle) -> RunStatus | None:
        """Poll remote Galaxy workflow invocation via bioblend."""
        client = self._get_bioblend_client()
        try:
            invocations = client.workflows.show_invocation(
                run_handle.run_id
            )
            state = invocations.get("state", "unknown")
            if state in ("done", "failed"):
                run_handle.status = "completed" if state == "done" else "failed"
                return RunStatus(
                    state=run_handle.status,
                    message=state,
                )
            return RunStatus(state="running", message=state)
        except Exception as e:
            logger.warning("Failed to poll Galaxy invocation: %s", e)
            return None

    def _check_completion_planemo(
        self, run_handle: RunHandle
    ) -> RunStatus | None:
        """Check planemo completion from log file."""
        log_path = Path(run_handle.work_dir) / "galaxy.log"
        if log_path.exists():
            content = log_path.read_text()
            if "Error" in content or "error" in content:
                run_handle.status = "failed"
                return RunStatus(
                    state="failed",
                    message="See galaxy.log for details",
                )
            if "Serving on" in content and "Shutting down" in content:
                run_handle.status = "completed"
                return RunStatus(state="completed")

        run_handle.status = "unknown"
        return RunStatus(
            state="unknown",
            message="Could not determine completion status",
        )

    def collect(self, run_handle: RunHandle) -> list[Any]:
        """Collect outputs from a completed Galaxy run.

        In planemo mode: discover files from the Galaxy work directory.
        In remote mode: download outputs via bioblend.
        """
        if self._config.mode == "remote":
            return self._collect_remote(run_handle)
        else:
            return self._collect_planemo(run_handle)

    def _collect_planemo(self, run_handle: RunHandle) -> list[Any]:
        """Collect outputs from local planemo Galaxy."""
        work_dir = Path(run_handle.work_dir)
        outputs: list[dict[str, Any]] = []

        # Look for output files in the Galaxy working directory
        galaxy_dir = work_dir / "galaxy"
        if galaxy_dir.exists():
            for f in galaxy_dir.rglob("*.dat"):
                if f.is_file():
                    outputs.append({
                        "path": str(f),
                        "name": f.name,
                        "size": f.stat().st_size,
                    })

        return outputs

    def _collect_remote(self, run_handle: RunHandle) -> list[Any]:
        """Download outputs from remote Galaxy via bioblend."""
        client = self._get_bioblend_client()
        outputs: list[dict[str, Any]] = []

        try:
            invocation = client.workflows.show_invocation(
                run_handle.run_id
            )
            history_id = invocation.get("history_id", "")
            if history_id:
                datasets = client.histories.show_history(
                    history_id, contents=True
                )
                for ds in datasets:
                    if ds.get("state") == "ok":
                        outputs.append({
                            "path": ds.get("file_name", ""),
                            "name": ds.get("name", ""),
                            "size": ds.get("file_size", 0),
                        })
        except Exception as e:
            logger.warning("Failed to collect Galaxy outputs: %s", e)

        return outputs
