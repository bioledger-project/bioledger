"""Galaxy adapter — local execution via planemo or remote via bioblend.

Implements all five ``ExecutionAdapter`` methods:
- ``submit_spec()``: run a workflow toolspec via Galaxy
- ``generate()``: produce a Galaxy .ga workflow definition for fan-out
- ``submit()``: submit the workflow to a Galaxy instance
- ``poll()``: check workflow invocation status
- ``collect()``: collect outputs from completed Galaxy history

Two modes:
- ``planemo`` (default): local Galaxy instance via planemo (pip-installable)
- ``remote``: connect to an existing Galaxy server via bioblend

Includes a tool-availability check: before running, the adapter queries
the Galaxy instance's tool panel to verify the toolspec's tool exists.
If not, errors with a clear message — no Docker fallback.
"""

from __future__ import annotations

import json
import logging
import shutil
import subprocess
import time
from pathlib import Path
from typing import Any

from bioledger.core.engines.conda_derive import resolve_container_from_spec
from bioledger.core.engines.config import GalaxyEngineConfig
from bioledger.core.engines.protocol import (
    RunHandle,
    RunStatus,
    WorkflowHandle,
    build_output_patterns,
    split_collection_inputs,
)

logger = logging.getLogger(__name__)


def _check_planemo_available() -> str:
    """Return the planemo executable path, or raise with install instructions."""
    exe = shutil.which("planemo")
    if exe is None:
        raise RuntimeError(
            "planemo is not installed. Install with: pip install bioledger[galaxy]"
        )
    return exe


def _resolve_container(spec: Any) -> str:
    """Resolve the container image from spec.container or spec.conda_deps.

    .. deprecated:: Use ``resolve_container_from_spec`` from
        ``conda_derive`` directly.
    """
    return resolve_container_from_spec(spec)


def _generate_galaxy_workflow(
    spec: Any,
    input_mapping: dict[str, str],
    artifact_path: Path,
) -> tuple[list[str], list[str]]:
    """Generate a Galaxy .ga workflow definition for fan-out.

    Returns (step_names, collection_inputs).
    """
    spec_outputs = getattr(spec, "outputs", {}) or {}
    tool_name = getattr(spec, "name", "tool")
    container_image = resolve_container_from_spec(spec)

    collection_inputs, single_inputs = split_collection_inputs(
        spec, input_mapping
    )

    # Build Galaxy workflow JSON
    tool_id = tool_name
    tool_version = "latest"
    if container_image and ":" in container_image:
        tool_version = container_image.split(":")[-1]

    # Build input connections
    input_connections: dict[str, dict] = {}
    for name in single_inputs:
        input_connections[name] = {"id": 0, "output_name": "output"}

    # Build outputs
    outputs: dict[str, dict] = {}
    for out_name in spec_outputs:
        outputs[out_name] = {"type": "data", "name": out_name}

    workflow = {
        "a_galaxy_workflow": "true",
        "format-version": "0.1",
        "name": f"BioLedger fan-out: {tool_name}",
        "annotation": f"Generated by BioLedger for {tool_name}",
        "steps": {
            "0": {
                "id": 0,
                "type": "data_input",
                "tool_id": None,
                "tool_version": None,
                "name": "Input dataset",
                "inputs": [{"name": "input"}],
                "position": {"left": 100, "top": 100},
            },
            "1": {
                "id": 1,
                "type": "tool",
                "tool_id": tool_id,
                "tool_version": tool_version,
                "name": tool_name,
                "input_connections": input_connections,
                "outputs": outputs,
                "position": {"left": 300, "top": 100},
            },
        },
    }

    # If collection inputs, add a data collection input step
    if collection_inputs:
        workflow["steps"]["2"] = {
            "id": 2,
            "type": "data_collection_input",
            "tool_id": None,
            "tool_version": None,
            "name": f"Input collection: {collection_inputs[0]}",
            "inputs": [{"name": collection_inputs[0]}],
            "position": {"left": 100, "top": 300},
        }
        # Wire the collection to the tool step
        workflow["steps"]["1"]["input_connections"][collection_inputs[0]] = {
            "id": 2,
            "output_name": "output",
        }

    artifact_path.parent.mkdir(parents=True, exist_ok=True)
    artifact_path.write_text(json.dumps(workflow, indent=2))
    return [tool_name], collection_inputs


class GalaxyAdapter:
    """Galaxy adapter for local (planemo) or remote (bioblend) execution.

    In planemo mode, launches a local Galaxy instance via planemo and
    submits workflows to it. In remote mode, connects to an existing
    Galaxy server via bioblend.

    Includes a tool-availability check before submission: queries the
    Galaxy instance's tool panel to verify the tool exists. If not,
    raises an error with a clear message — no Docker fallback.
    """

    _engine_name = "galaxy"

    def __init__(self, config: GalaxyEngineConfig | None = None) -> None:
        self._config = config or GalaxyEngineConfig()
        self._bioblend_client = None

    @property
    def executable(self) -> str:
        if self._config.executable:
            return self._config.executable
        if self._config.mode == "planemo":
            return _check_planemo_available()
        raise RuntimeError(
            "Remote Galaxy mode requires bioblend. "
            "Install with: pip install bioledger[galaxy]"
        )

    def _detect_version(self) -> str:
        """Detect the planemo/galaxy version by shelling out once; cache on the instance."""
        if hasattr(self, "_cached_version"):
            return self._cached_version
        from bioledger.core.engines.versions import detect_engine_version
        try:
            exe = self.executable
        except RuntimeError:
            self._cached_version = "galaxy unknown"
            return self._cached_version
        self._cached_version = detect_engine_version(self._engine_name, exe)
        return self._cached_version

    def _get_bioblend_client(self):
        """Get or create a bioblend GalaxyClient for remote mode."""
        if self._bioblend_client is not None:
            return self._bioblend_client
        try:
            from bioblend.galaxy import GalaxyInstance
        except ImportError:
            raise RuntimeError(
                "bioblend is not installed. "
                "Install with: pip install bioledger[galaxy]"
            )
        self._bioblend_client = GalaxyInstance(
            url=self._config.url,
            key=self._config.api_key or "",
        )
        return self._bioblend_client

    def _get_galaxy_instance(self):
        """Get a bioblend GalaxyInstance for either planemo or remote mode.

        In planemo mode, connects to the local planemo server at the configured port.
        In remote mode, connects to the configured Galaxy server.
        """
        if self._config.mode == "planemo":
            try:
                from bioblend.galaxy import GalaxyInstance
            except ImportError:
                raise RuntimeError(
                    "bioblend is not installed. "
                    "Install with: pip install bioledger[galaxy]"
                )
            return GalaxyInstance(url=f"http://localhost:{self._config.planemo_port}", key="")
        else:
            return self._get_bioblend_client()

    def _check_tool_availability(self, tool_id: str) -> None:
        """Check if a tool is available in the Galaxy instance.

        Raises RuntimeError if the tool is not found — no Docker fallback.
        """
        if self._config.mode == "remote":
            client = self._get_bioblend_client()
            tools = client.tools.get_tools()
            tool_ids = {t.get("id", "") for t in tools}
            if tool_id not in tool_ids:
                raise RuntimeError(
                    f"Tool '{tool_id}' is not available in this Galaxy instance "
                    f"({self._config.url}). No Docker fallback — install the "
                    f"tool in Galaxy or use a different engine."
                )
        else:
            # planemo mode: check if the tool is in the local tool panel
            # For now, we trust that planemo serves the tool if it's in
            # the configured tool directory. A full check would query
            # the planemo server's API.
            logger.info(
                "Tool availability check skipped in planemo mode for %s",
                tool_id,
            )

    def submit_spec(
        self,
        spec: Any,
        input_mapping: dict[str, str],
        params: dict[str, Any],
        work_dir: Path,
        tool_dir: Path | None = None,
    ) -> RunHandle:
        """Run a single workflow toolspec via Galaxy.

        If ``tool_dir`` is provided (discovered Tool Shed XML), delegates to
        ``generate()`` + ``submit()``: the ``generate()`` method builds a
        ``.ga`` workflow from the spec, and ``submit()`` invokes it on the
        Galaxy instance (planemo or remote).

        If ``tool_dir`` is NOT provided (user-defined spec), runs the spec's
        ``command`` field directly as a subprocess — the command must be a
        valid Galaxy/planemo invocation (e.g. ``planemo run tool.xml ...``).
        Bypasses ``.ga`` workflow generation and bioblend entirely.
        """
        if tool_dir:
            handle = self.generate(spec, input_mapping)
            handle.metadata["tool_dir"] = str(tool_dir)
            return self.submit(handle, input_mapping, params, work_dir)

        # User-defined spec: run the command directly as a subprocess
        work_dir = Path(work_dir)
        work_dir.mkdir(parents=True, exist_ok=True)

        from bioledger.toolspec import get_jinja_env

        command_template = spec.command if hasattr(spec, "command") else ""
        if not command_template:
            raise RuntimeError(
                "User-defined Galaxy spec has no command field — cannot "
                "run directly. Provide a valid Galaxy/planemo invocation "
                "in the command field, or use a discovered tool with tool_dir."
            )

        context = {
            "inputs": {name: f"${{{name}}}" for name in input_mapping},
            "outputs": {"_dir": str(work_dir)},
            "parameters": params,
        }
        try:
            rendered_cmd = get_jinja_env().from_string(command_template).render(context)
        except Exception as e:
            raise RuntimeError(f"Failed to render Galaxy command: {e}") from e

        log_path = work_dir / "galaxy.log"
        log_file = open(log_path, "w")
        try:
            import shlex
            proc = subprocess.Popen(
                shlex.split(rendered_cmd),
                cwd=str(work_dir),
                stdout=log_file,
                stderr=subprocess.STDOUT,
                start_new_session=True,
            )
        finally:
            log_file.close()

        run_id = str(proc.pid)
        process_start_time = None
        try:
            import psutil
            process_start_time = psutil.Process(proc.pid).create_time()
        except Exception:
            pass

        return RunHandle(
            executor="galaxy",
            run_id=run_id,
            entry_id="",
            work_dir=work_dir,
            status="running",
            process_start_time=process_start_time,
            metadata={"engine_version": self._detect_version()},
        )

    def generate(
        self,
        spec: Any,
        input_mapping: dict[str, str],
        extra_args: list[str] | None = None,
    ) -> WorkflowHandle:
        """Generate a Galaxy .ga workflow definition for fan-out.

        Galaxy fan-out is not yet supported — this method raises
        ``NotImplementedError`` with install instructions for Snakemake or
        Nextflow. Galaxy is still supported for single-tool runs and Tool
        Shed discovery via ``submit_spec()``.
        """
        raise NotImplementedError(
            "Galaxy fan-out is not yet supported. Fan-out requires Snakemake or Nextflow. "
            "Install one with: pip install bioledger[snakemake] or pip install bioledger[nextflow]. "
            "Galaxy is supported for single-tool runs and Tool Shed discovery."
        )

        step_names, collection_inputs = _generate_galaxy_workflow(
            spec, input_mapping, artifact_path
        )

        output_patterns = build_output_patterns(spec)

        return WorkflowHandle(
            executor="galaxy",
            artifact_path=artifact_path,
            step_inventory=step_names,
            container_image="",
            input_mapping=input_mapping,
            output_patterns=output_patterns,
            metadata={
                "extra_args": extra_args or [],
                "collection_inputs": collection_inputs,
            },
        )

    def submit(
        self,
        handle: WorkflowHandle,
        input_mapping: dict[str, str],
        params: dict[str, Any],
        work_dir: Path,
    ) -> RunHandle:
        """Submit the generated Galaxy workflow.

        In planemo mode: starts a local Galaxy server and submits the workflow.
        In remote mode: submits to the configured Galaxy server via bioblend.
        """
        work_dir = Path(work_dir)
        work_dir.mkdir(parents=True, exist_ok=True)

        # Copy the workflow to the work dir
        ga_path = work_dir / "workflow.ga"
        ga_path.write_text(handle.artifact_path.read_text())

        # Extract tool_id from the .ga workflow JSON for availability check
        tool_id = "unknown"
        try:
            ga_data = json.loads(ga_path.read_text())
            for step in ga_data.get("steps", {}).values():
                if step.get("type") == "tool" and step.get("tool_id"):
                    tool_id = step["tool_id"]
                    break
        except Exception:
            pass
        self._check_tool_availability(tool_id)

        if self._config.mode == "planemo":
            return self._submit_planemo(handle, work_dir, ga_path, input_mapping)
        else:
            return self._submit_remote(handle, work_dir, ga_path, input_mapping)

    def _submit_planemo(
        self, handle: WorkflowHandle, work_dir: Path, ga_path: Path,
        input_mapping: dict[str, str] | None = None,
    ) -> RunHandle:
        """Submit via planemo local Galaxy instance.

        Starts planemo serve, waits for the server to be ready, then
        imports the workflow, uploads inputs, and invokes it via bioblend.
        Returns a RunHandle with the Galaxy invocation ID as run_id and
        the planemo PID stored in metadata for cleanup.
        """
        cmd = [
            self.executable,
            "serve",
            "galaxy",
            "--galaxy-root",
            str(work_dir / "galaxy"),
            "--port", str(self._config.planemo_port),
        ]
        # Support --tool_dir for discovered tools (Phase 3A)
        tool_dir = handle.metadata.get("tool_dir")
        if tool_dir:
            cmd.extend(["--tool_dir", str(tool_dir)])

        extra_args = handle.metadata.get("extra_args", [])
        cmd.extend(extra_args)
        cmd.extend(self._config.extra_args)

        log_path = work_dir / "galaxy.log"
        log_file = open(log_path, "w")
        try:
            proc = subprocess.Popen(
                cmd,
                cwd=str(work_dir),
                stdout=log_file,
                stderr=subprocess.STDOUT,
                start_new_session=True,
            )
        finally:
            log_file.close()
        planemo_pid = proc.pid

        # Wait for the Galaxy server to be ready
        import httpx

        server_url = f"http://localhost:{self._config.planemo_port}/api/version"
        for _ in range(30):
            try:
                resp = httpx.get(server_url, timeout=2.0)
                if resp.status_code == 200:
                    break
            except Exception:
                pass
            time.sleep(2)
        else:
            raise RuntimeError(
                "planemo server did not become ready within 60 seconds"
            )

        # Connect via bioblend and invoke the workflow
        gi = self._get_galaxy_instance()

        # Import the workflow
        workflow_content = ga_path.read_text()
        imported = gi.workflows.import_workflow_dict(
            json.loads(workflow_content)
        )
        workflow_id = imported.get("id", "")

        # Create a new history
        history = gi.histories.create_history(
            name=f"BioLedger_{int(time.time())}"
        )
        history_id = history.get("id", "")

        # Upload input files to the history
        input_dataset_map: dict[str, dict] = {}
        inputs = input_mapping or handle.input_mapping
        for input_name, file_path in inputs.items():
            if file_path and Path(file_path).exists():
                upload_result = gi.tools.upload_file(
                    file_path,
                    history_id,
                    file_name=input_name,
                )
                dataset_id = upload_result.get("outputs", [{}])[0].get("id", "")
                input_dataset_map[input_name] = {"id": dataset_id, "src": "hda"}

        # Invoke the workflow
        invocation = gi.workflows.invoke_workflow(
            workflow_id,
            history_id=history_id,
            inputs=input_dataset_map,
        )
        invocation_id = invocation.get("id", "")

        return RunHandle(
            executor="galaxy",
            run_id=invocation_id,
            entry_id="",
            work_dir=work_dir,
            status="running",
            metadata={"planemo_pid": planemo_pid, "engine_version": self._detect_version()},
        )

    def _submit_remote(
        self, handle: WorkflowHandle, work_dir: Path, ga_path: Path,
        input_mapping: dict[str, str] | None = None,
    ) -> RunHandle:
        """Submit via bioblend to a remote Galaxy server."""
        client = self._get_bioblend_client()

        # Import the workflow
        workflow_content = ga_path.read_text()
        imported = client.workflows.import_workflow_dict(
            json.loads(workflow_content)
        )
        workflow_id = imported.get("id", "")

        # Create a new history
        history = client.histories.create_history(
            name=f"BioLedger_{int(time.time())}"
        )
        history_id = history.get("id", "")

        # Upload input files to the history
        input_dataset_map: dict[str, dict] = {}
        inputs = input_mapping or handle.input_mapping
        for input_name, file_path in inputs.items():
            if file_path and Path(file_path).exists():
                upload_result = client.tools.upload_file(
                    file_path,
                    history_id,
                    file_name=input_name,
                )
                dataset_id = upload_result.get("outputs", [{}])[0].get("id", "")
                input_dataset_map[input_name] = {"id": dataset_id, "src": "hda"}

        # Run the workflow
        invocation = client.workflows.invoke_workflow(
            workflow_id,
            history_id=history_id,
            inputs=input_dataset_map,
        )
        invocation_id = invocation.get("id", "")

        return RunHandle(
            executor="galaxy",
            run_id=invocation_id,
            entry_id="",
            work_dir=work_dir,
            status="running",
            metadata={"engine_version": self._detect_version()},
        )

    def poll(self, run_handle: RunHandle) -> RunStatus | None:
        """Check if the Galaxy workflow invocation is still running.

        Both planemo and remote modes use bioblend to poll the invocation state.
        """
        return self._poll_invocation(run_handle)

    def _poll_invocation(self, run_handle: RunHandle) -> RunStatus | None:
        """Poll Galaxy workflow invocation via bioblend (unified for both modes)."""
        gi = self._get_galaxy_instance()
        try:
            invocation = gi.workflows.show_invocation(
                run_handle.run_id
            )
            state = invocation.get("state", "unknown")
            if state in ("done", "failed"):
                run_handle.status = "completed" if state == "done" else "failed"
                return RunStatus(
                    state=run_handle.status,
                    message=state,
                )
            return RunStatus(state="running", message=state)
        except Exception as e:
            logger.warning("Failed to poll Galaxy invocation: %s", e)
            return None

    def _shutdown_planemo(self, run_handle: RunHandle) -> None:
        """Shut down the planemo server process after completion."""
        planemo_pid = run_handle.metadata.get("planemo_pid")
        if planemo_pid:
            try:
                subprocess.run(
                    ["kill", "-TERM", str(planemo_pid)],
                    capture_output=True,
                    timeout=5,
                )
            except Exception as e:
                logger.warning("Failed to shut down planemo: %s", e)

    def collect(self, run_handle: RunHandle) -> list[Any]:
        """Collect outputs from a completed Galaxy run.

        Both planemo and remote modes use bioblend to download outputs.
        In planemo mode, also shuts down the planemo server after collection.
        """
        outputs = self._collect_bioblend(run_handle)

        if self._config.mode == "planemo":
            self._shutdown_planemo(run_handle)

        return outputs

    def _collect_bioblend(self, run_handle: RunHandle) -> list[Any]:
        """Download outputs from Galaxy via bioblend (unified for both modes)."""
        gi = self._get_galaxy_instance()
        outputs: list[dict[str, Any]] = []

        try:
            invocation = gi.workflows.show_invocation(
                run_handle.run_id
            )
            history_id = invocation.get("history_id", "")
            if history_id:
                datasets = gi.histories.show_history(
                    history_id, contents=True
                )
                for ds in datasets:
                    if ds.get("state") == "ok":
                        outputs.append({
                            "path": ds.get("file_name", ""),
                            "name": ds.get("name", ""),
                            "size": ds.get("file_size", 0),
                        })
        except Exception as e:
            logger.warning("Failed to collect Galaxy outputs: %s", e)

        return outputs
